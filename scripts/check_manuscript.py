"""Structural checks of the Springer Nature manuscript (paper/springer/hemishift_sn.tex).

Checks what a script can check: comments and leftover markers, citation coverage, dangling
and unused labels, float order, lone subsections, section openers, dashes and compound hyphens
in body text, the abstract rules, abbreviations at first use, figure files and wording about
AI. It cannot check whether a reference is real, whether a number matches its source, or
whether a sentence that points at a float says anything useful.

Usage: python scripts/check_manuscript.py [path/to/manuscript.tex]
"""

import re
import sys
from pathlib import Path

TEX = Path(sys.argv[1] if len(sys.argv) > 1 else "paper/springer/hemishift_sn.tex")
BIB = TEX.with_name("references.bib")
# dashes that belong to proper names or identifiers
ALLOWED_HYPHENS = {"Fugl-Meyer", "MNE-Python", "HEFMI-ICH", "CLEAN-MI", "Mann--Whitney"}
ID = re.compile(r"\bH-[CER]\d\b")
ABBREVIATIONS = ("BCI", "EEG", "EOG", "ICA", "NIHSS", "CI", "SVM", "ERD", "CSP", "LSL", "BIDS", "MOABB")


def strip_arguments(text):
    """Body text without keys, paths, URLs, typewriter text and math."""
    text = re.sub(r"\\(label|ref|eqref|cite|includegraphics|url|email|texttt|bibliography)(\[[^\]]*\])?\{[^}]*\}", " ", text)
    text = re.sub(r"\$[^$]*\$", " ", text)
    text = re.sub(r"\\begin\{(equation|align)\}.*?\\end\{\1\}", " ", text, flags=re.S)
    return text


def main():
    tex = TEX.read_text(encoding="utf-8")
    problems = []

    # comments and markers
    for i, line in enumerate(tex.splitlines(), 1):
        if re.search(r"(?<!\\)%", line):
            problems.append(f"line {i}: comment character")
    # IEEE fills the \history and \doi lines on publication; their xxxx placeholders belong to the template
    scanned = "\n".join(line for line in tex.splitlines() if not line.startswith(("\\history", "\\doi")))
    for marker in ("ZZZ", "TODO", "FIXME", "XXX", "[AUTHORS", "placeholder"):
        if marker.lower() in scanned.lower():
            problems.append(f"leftover marker {marker!r}")
    # an author's research interests may name the field; the biographies are left out of this check
    no_bios = re.sub(r"\\begin\{IEEEbiography\}.*?\\end\{IEEEbiography\}", " ", tex, flags=re.S)
    for word in ("Claude", "ChatGPT", "language model", "generated by AI", "AI tool", "artificial intelligence"):
        if word.lower() in no_bios.lower():
            problems.append(f"mentions {word!r}")

    # citations
    cited = []
    for m in re.finditer(r"\\cite\{([^}]*)\}", tex):
        cited += [k.strip() for k in m.group(1).split(",")]
    bib_keys = re.findall(r"^@\w+\{([^,]+),", BIB.read_text(encoding="utf-8"), flags=re.M)
    for k in sorted(set(cited) - set(bib_keys)):
        problems.append(f"cited but not in the bibliography: {k}")
    for k in sorted(set(bib_keys) - set(cited)):
        problems.append(f"in the bibliography but never cited: {k}")
    for m in re.finditer(r"(.)\\cite\{", tex):
        if m.group(1) != "~":
            problems.append(f"citation without a non-breaking space: ...{tex[max(0, m.start() - 30):m.start() + 6]!r}")

    # labels and references
    labels = re.findall(r"\\label\{([^}]*)\}", tex)
    refs = re.findall(r"\\(?:ref|eqref)\{([^}]*)\}", tex)
    for r in sorted(set(refs) - set(labels)):
        problems.append(f"reference to an undefined label: {r}")
    for lab in labels:
        if lab.startswith(("fig:", "tab:", "eq:")) and lab not in refs:
            problems.append(f"float or equation never referenced: {lab}")

    # floats in citation order
    for kind, prefix in (("figure", "fig:"), ("table", "tab:")):
        declared = [m.group(1) for m in re.finditer(r"\\begin\{" + kind + r"\*?\}.*?\\label\{(" + prefix + r"[^}]*)\}", tex, flags=re.S)]
        first_ref = []
        for m in re.finditer(r"\\ref\{(" + prefix + r"[^}]*)\}", tex):
            if m.group(1) not in first_ref:
                first_ref.append(m.group(1))
        if declared != first_ref:
            problems.append(f"{kind}s declared in the order {declared} but first cited in the order {first_ref}")

    # section structure
    end = "\\backmatter" if "\\backmatter" in tex else "\\bibliographystyle"  # Springer or IEEE layout
    body = tex.split("\\maketitle", 1)[1].split(end, 1)[0]
    sections = re.split(r"\\section\{", body)[1:]
    for sec in sections:
        title = sec.split("}", 1)[0]
        subs = re.split(r"\\subsection\{", sec)
        if len(subs) == 2:
            problems.append(f"section '{title}' has exactly one subsection")
        if len(subs) > 1:
            opener = re.sub(r"\\label\{[^}]*\}", "", subs[0].split("}", 1)[1]).strip()
            if len(opener.split()) < 15:
                problems.append(f"section '{title}' has no opening paragraph before its subsections")
        for sub in subs[1:]:
            if len(re.split(r"\\subsubsection\{", sub)) == 2:
                problems.append(f"subsection '{sub.split('}', 1)[0]}' has exactly one subsubsection")
        if title.startswith("Introduction") and re.search(r"\\(sub)+section|\\paragraph", sec):
            problems.append("the Introduction has subheadings")

    # dashes and compound hyphens in body text (abstract included)
    found = (re.search(r"\\abstract\{(.*?)\}\n", tex, flags=re.S)
             or re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", tex, flags=re.S))
    abstract = found.group(1)
    print(f"abstract: {len(abstract.split())} words")
    text = strip_arguments(abstract + "\n" + body)
    for name in ALLOWED_HYPHENS:
        text = text.replace(name, " ")
    text = ID.sub(" ", text)
    for m in re.finditer(r"---|--|\u2014|\u2013", text):
        problems.append(f"dash in body text: ...{text[max(0, m.start() - 30):m.end() + 30]!r}")
    for m in re.finditer(r"[A-Za-z]+-[A-Za-z]+", text):
        problems.append(f"compound hyphen in body text: {m.group(0)!r}")
    # the work is described as done in this study, never as a repetition of earlier runs
    for m in re.finditer(r"\b(reproduc\w*|re-?run\w*|recomput\w*|replicat\w*|repeat\w*|again|first logged|replay\w*|rebuild\w*)\b",
                         text, flags=re.I):
        problems.append(f"repetition wording: {m.group(0)!r} in ...{text[max(0, m.start() - 40):m.end() + 20]!r}")

    # abstract rules
    if re.search(r"\\cite|\$|\\begin\{equation|\(\s*p\s*=|-", abstract):
        problems.append("abstract has a citation, math, a parenthetical statistic or a dash")
    if "\n\n" in abstract.strip():
        problems.append("abstract has more than one paragraph")

    # abbreviations: the first use in the body must be the defining one, "(ABBR)" or "(ABBRs)"
    for abbr in ABBREVIATIONS:
        m = re.search(r"\b" + abbr + r"s?\b", body)
        if m and not re.match(r"\(" + abbr + r"s?\)", body[m.start() - 1:m.end() + 1]):
            problems.append(f"abbreviation {abbr} used before it is defined: ...{body[max(0, m.start() - 40):m.end() + 10]!r}")

    # figure files
    for path in re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}", tex):
        if not (TEX.parent / path).exists():
            problems.append(f"missing figure file {path}")

    words = len(re.sub(r"\\[a-zA-Z]+|[{}\[\]$\\]", " ", body).split())
    print(f"{TEX}: about {words} words in the body, {len(set(cited))} references cited, "
          f"{len(re.findall(r'begin.figure.', tex))} figures, {len(re.findall(r'begin.table.', tex))} tables")
    for p in problems:
        print("  PROBLEM:", p)
    print("no problems found" if not problems else f"{len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
